-- Many-to-many relationship between issues and epics
create table if not exists public.issue_epics (
  id         bigint generated by default as identity primary key,
  issue_id   bigint not null references public.issues(id) on delete cascade,
  epic_id    bigint not null references public.issues(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (issue_id, epic_id)
);

alter table public.issue_epics enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'issue_epics' and policyname = 'Users can read issue_epics') then
    create policy "Users can read issue_epics" on public.issue_epics for select using (auth.role() = 'authenticated');
  end if;
end;
$$;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'issue_epics' and policyname = 'Users can insert issue_epics') then
    create policy "Users can insert issue_epics" on public.issue_epics for insert with check (auth.role() = 'authenticated');
  end if;
end;
$$;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'issue_epics' and policyname = 'Users can delete issue_epics') then
    create policy "Users can delete issue_epics" on public.issue_epics for delete using (auth.role() = 'authenticated');
  end if;
end;
$$;

create index if not exists idx_issue_epics_issue on public.issue_epics(issue_id);
create index if not exists idx_issue_epics_epic on public.issue_epics(epic_id);

-- Migrate existing parent_epic_id data to the new join table
insert into public.issue_epics (issue_id, epic_id)
select id, parent_epic_id from public.issues
where parent_epic_id is not null
on conflict (issue_id, epic_id) do nothing;
