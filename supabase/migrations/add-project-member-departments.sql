-- Multiple departments per project member.
-- Additive migration: the legacy `project_members.department` column is kept
-- untouched, so all existing reads/writes continue to work. Current values are
-- copied into the new table so no data is lost.

create table if not exists public.project_member_departments (
  id          bigint generated by default as identity primary key,
  member_id   bigint not null references public.project_members(id) on delete cascade,
  department  text not null check (btrim(department) <> ''),
  created_at  timestamptz not null default now(),
  unique (member_id, department)
);

alter table public.project_member_departments enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'project_member_departments' and policyname = 'Users can read project_member_departments') then
    create policy "Users can read project_member_departments" on public.project_member_departments for select using (auth.role() = 'authenticated');
  end if;
end;
$$;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'project_member_departments' and policyname = 'Users can insert project_member_departments') then
    create policy "Users can insert project_member_departments" on public.project_member_departments for insert with check (auth.role() = 'authenticated');
  end if;
end;
$$;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'project_member_departments' and policyname = 'Users can update project_member_departments') then
    create policy "Users can update project_member_departments" on public.project_member_departments for update using (auth.role() = 'authenticated');
  end if;
end;
$$;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'project_member_departments' and policyname = 'Users can delete project_member_departments') then
    create policy "Users can delete project_member_departments" on public.project_member_departments for delete using (auth.role() = 'authenticated');
  end if;
end;
$$;

create index if not exists idx_project_member_departments_member on public.project_member_departments(member_id);

-- Backfill from the legacy single-value column (idempotent).
insert into public.project_member_departments (member_id, department)
select id, btrim(department)
from public.project_members
where department is not null and btrim(department) <> ''
on conflict (member_id, department) do nothing;
